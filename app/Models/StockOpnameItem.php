<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * Represents one product line in a stock opname.
 *
 * COLUMN BEHAVIOUR:
 *   system_stock    — NOT NULL. Snapshot of current_stock at opname creation time.
 *   physical_stock  — NULLABLE. NULL = "not yet counted" (draft only).
 *                     0 = counted, result is zero (valid, not empty).
 *   difference      — GENERATED STORED (physical_stock - system_stock).
 *                     NULL when physical_stock is NULL. Never written by the app.
 *   difference_reason — NULLABLE. Explanation for any discrepancy.
 *
 * RULES enforced at the service/request layer (not the model):
 *   - physical_stock may be NULL only while parent opname is draft.
 *   - Confirmation of the parent opname is blocked if any item has
 *     physical_stock IS NULL.
 *   - 0 is a valid physical count; never treat it as "not counted".
 */
class StockOpnameItem extends Model
{
    public $timestamps = false;

    protected $fillable = [
        'stock_opname_id',
        'product_id',
        'system_stock',
        'physical_stock',       // nullable — see class docblock
        'difference_reason',
        // 'difference' is intentionally absent: it is GENERATED by the database
    ];

    protected function casts(): array
    {
        return [
            'system_stock' => 'decimal:3',
            'physical_stock' => 'decimal:3',    // cast to string (3dp) or null
            'difference' => 'decimal:3',        // read-only generated column
        ];
    }

    // ── Relationships ─────────────────────────────────────────────────────

    public function stockOpname(): BelongsTo
    {
        return $this->belongsTo(StockOpname::class);
    }

    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class);
    }

    // ── Helpers ───────────────────────────────────────────────────────────

    /** True when the item has been physically counted. */
    public function isCounted(): bool
    {
        return $this->physical_stock !== null;
    }

    /**
     * True when there is a discrepancy between physical and system stock.
     * Returns false when not yet counted (physical_stock is NULL).
     */
    public function hasDiscrepancy(): bool
    {
        if (! $this->isCounted()) {
            return false;
        }

        return bccomp(
            (string) $this->physical_stock,
            (string) $this->system_stock,
            3
        ) !== 0;
    }
}
